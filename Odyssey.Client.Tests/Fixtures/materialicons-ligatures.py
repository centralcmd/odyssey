"""Regenerates materialicons-ligatures.txt from the bundled Material Icons font (issue #345).

Every TagIcons key must be a ligature the self-hosted font draws; a key it lacks renders as literal
text. TagIconFontLigatureTests checks the catalogue against the list this writes, and the recorded
SHA-256 against the font, so swapping the font fails the build until this is re-run.

Needs fontTools with WOFF2 support (Fedora: dnf install python3-fonttools python3-brotli).

    python3 -I Odyssey.Client.Tests/Fixtures/materialicons-ligatures.py
"""
import glob
import hashlib
import os
import sys

from fontTools.ttLib import TTFont

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))
fonts = glob.glob(os.path.join(root, "Odyssey.Client", "wwwroot", "fonts", "materialicons-*.woff2"))
if len(fonts) != 1:
    sys.exit(f"expected exactly one materialicons-*.woff2, found {len(fonts)}")

font_path = fonts[0]
font = TTFont(font_path)
glyph_to_char = {glyph: chr(code) for code, glyph in font.getBestCmap().items()}

names = set()
for lookup in font["GSUB"].table.LookupList.Lookup:
    for table in lookup.SubTable:
        if lookup.LookupType == 7:
            table = table.ExtSubTable
        for first, ligatures in (getattr(table, "ligatures", None) or {}).items():
            for ligature in ligatures:
                try:
                    names.add(glyph_to_char[first] + "".join(glyph_to_char[c] for c in ligature.Component))
                except KeyError:
                    pass

with open(font_path, "rb") as handle:
    digest = hashlib.sha256(handle.read()).hexdigest()

with open(os.path.join(here, "materialicons-ligatures.txt"), "w", encoding="utf-8", newline="\n") as out:
    out.write(f"# font: {os.path.basename(font_path)}\n")
    out.write(f"# sha256: {digest}\n")
    out.write("# Generated by materialicons-ligatures.py; do not edit by hand.\n")
    for name in sorted(names):
        out.write(name + "\n")
